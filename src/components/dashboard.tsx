function ActivityTable({ rows, demo, onRecover }: { rows: Activity[]; demo: boolean; onRecover?:(hash:string)=>void }) {
  if (!rows.length)
    return (
      <div className="empty">
        <History size={28} />
        <h3>A clean slate.</h3>
        <p>
          No activity in this view. Proposals appear before transactions;
          pending hashes remain visible after refresh.
        </p>
      </div>
    );
  return (
    <div className="table-wrap">
      <table>
        <thead>
          <tr>
            <th>ACTION</th>
            <th>OUTCOME</th>
            <th>WHEN</th>
            <th>EVIDENCE</th>
          </tr>
        </thead>
        <tbody>
          {rows.map((a) => (
            <tr key={a.id}>
              <td>
                <strong>{a.summary}</strong>
                {a.reason && <small>{a.reason}</small>}
              </td>
              <td>
                <span
                  className={`badge ${a.kind === "preflight_rejection" || a.kind === "onchain_failure" ? "orange" : a.kind === "confirmed_execution" ? "lime" : ""}`}
                >
                  {demo ? "SAMPLE · " : ""}
                  {kindLabels[a.kind]}
                </span>
              </td>
              <td style={{ whiteSpace: "nowrap" }}>
                {demo
                  ? "Demo timeline"
                  : new Date(a.created_at).toLocaleTimeString()}
                <small>
                  {demo
                    ? "Illustrative only"
                    : new Date(a.created_at).toLocaleDateString()}
                </small>
              </td>
              <td>
                {a.tx_hash && onRecover && (a.kind==='submitted'||a.kind==='broadcast_unknown') && a.id!==a.tx_hash && <button className="text-link" onClick={()=>onRecover(a.tx_hash!)}>Recover saved transaction</button>}
                {a.tx_hash && !demo ? (
                  <a
                    href={`${EXPLORER}/transaction/${a.tx_hash}`}
                    target="_blank"
                    rel="noreferrer"
                  >
                    {short(a.tx_hash)} ↗
                  </a>
                ) : (
                  <span className="muted">
                    {demo ? "No real transaction" : "No onchain transaction"}
                  </span>
                )}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
